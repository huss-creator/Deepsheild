"""
forensics/metadata.py — Image Metadata (EXIF) Extraction

What is EXIF metadata?
    EXIF (Exchangeable Image File Format) is data embedded in image files
    by cameras and software. It can include:
        - Camera model and manufacturer
        - Lens information
        - GPS coordinates
        - Date and time of capture
        - Software used to process or edit the image
        - Exposure settings

How is this forensically relevant?
    - If editing software (e.g. Photoshop, GIMP) is detected in the EXIF,
      it indicates the image has been processed or edited.
    - Missing EXIF data may suggest the image was downloaded from the internet,
      screenshot-captured, or stripped of metadata.
    - AI-generated images often have no EXIF data at all.

IMPORTANT DISCLAIMER:
    Metadata is supporting forensic evidence ONLY.
    - EXIF can be easily added, removed, or modified.
    - Missing EXIF does NOT prove an image is fake.
    - Present EXIF does NOT prove an image is real.
    - This module provides context, not conclusions.

Requirements:
    pip install Pillow
    (Already in requirements.txt)
"""

import os
import json
import logging

logger = logging.getLogger(__name__)

# Known editing software keywords to flag as forensically notable
# Matched as WHOLE WORDS/PHRASES (so 'ai' no longer matches 'Fujifilm MainBoard',
# 'Microsoft Paint' or 'Gaia GPS').
EDITING_SOFTWARE_KEYWORDS = [
    'photoshop', 'gimp', 'lightroom', 'premiere', 'illustrator',
    'affinity', 'corel', 'paintshop', 'capture one', 'darktable',
    'rawtherapee', 'pixelmator', 'snapseed', 'facetune', 'meitu',
    'stable diffusion', 'midjourney', 'dall-e', 'dall·e', 'firefly', 'image generator',
    'ai generated', 'ai-generated', 'generated by ai', 'synthetic',
]
import re as _re
_EDITING_RE = _re.compile(r'(?<![a-z0-9])(?:' + '|'.join(_re.escape(k) for k in EDITING_SOFTWARE_KEYWORDS) + r')(?![a-z0-9])')


def match_editing_software(software: str) -> bool:
    return bool(_EDITING_RE.search((software or '').lower()))

# EXIF tag names we want to extract (using Pillow's tag ID approach)
# These are the most forensically relevant EXIF fields
# Tags that can identify a person, device or location. They are NEVER stored or
# displayed; only their presence is recorded (see meta_note).
SENSITIVE_EXIF_TAG_NAMES = {
    'GPSInfo', 'MakerNote', 'UserComment', 'Artist', 'Copyright', 'HostComputer',
    'ImageUniqueID', 'BodySerialNumber', 'LensSerialNumber', 'CameraOwnerName',
    'OwnerName', 'SerialNumber', 'XPAuthor', 'XPComment', 'XPKeywords', 'XPSubject',
    'XPTitle', 'ImageDescription', 'XMLPacket',
}
_SENSITIVE_INFO_KEY_FRAGMENTS = ('gps', 'author', 'artist', 'comment', 'description',
                                 'xmp', 'serial', 'owner', 'copyright', 'software_user')


def _is_sensitive_info_key(key: str) -> bool:
    k = key.lower()
    return any(fragment in k for fragment in _SENSITIVE_INFO_KEY_FRAGMENTS)


INTERESTING_EXIF_TAGS = {
    271:  'Camera Make',
    272:  'Camera Model',
    305:  'Software',
    306:  'Date/Time Modified',
    315:  'Artist',
    316:  'Host Computer',
    36867: 'Date/Time Original',
    36868: 'Date/Time Digitized',
    37510: 'User Comment',
    40093: 'Windows XP Author',
    40095: 'Windows XP Keywords',
}


def extract_metadata(image_path):
    """
    Extract EXIF and basic file metadata from an image.

    Args:
        image_path (str): Absolute path to the image file.

    Returns:
        dict:
            meta_format (str):       File format ('JPEG', 'PNG', etc.)
            meta_width (int):        Image width in pixels.
            meta_height (int):       Image height in pixels.
            meta_mode (str):         Color mode ('RGB', 'RGBA', 'L', etc.)
            meta_file_size_bytes (int): File size in bytes.
            meta_file_size_display (str): Human-readable file size.
            meta_has_exif (bool):    True if EXIF data was found.
            meta_camera_make (str):  Camera manufacturer.
            meta_camera_model (str): Camera model.
            meta_software (str):     Software used to create/edit.
            meta_datetime (str):     Date/time from EXIF.
            meta_is_editing_software (bool): True if editing software detected.
            meta_editing_software_name (str): Name of detected editing software.
            meta_raw_json (str):     JSON string of all extracted EXIF fields.
            meta_exif_count (int):   Number of EXIF tags found.
            meta_note (str):         Forensic interpretation note.
            success (bool):
            error (str):
    """
    result = {
        'meta_format': 'Unknown',
        'meta_width': 0,
        'meta_height': 0,
        'meta_mode': 'Unknown',
        'meta_file_size_bytes': 0,
        'meta_file_size_display': 'Unknown',
        'meta_has_exif': False,
        'meta_camera_make': '',
        'meta_camera_model': '',
        'meta_software': '',
        'meta_datetime': '',
        'meta_is_editing_software': False,
        'meta_editing_software_name': '',
        'meta_raw_json': '{}',
        'meta_exif_count': 0,
        'meta_note': 'Metadata analysis was not available.',
        'success': False,
        'error': '',
    }

    try:
        from PIL import Image, ExifTags  # noqa: F401  (availability probe)
        from PIL.ExifTags import TAGS

        # --- Step 1: Get basic file info ---
        try:
            file_size = os.path.getsize(image_path)
            result['meta_file_size_bytes'] = file_size
            result['meta_file_size_display'] = _format_file_size(file_size)
        except Exception:
            pass

        # --- Step 2: Open image and get basic properties ---
        img = Image.open(image_path)
        result['meta_format'] = img.format or 'Unknown'
        result['meta_width']  = img.width
        result['meta_height'] = img.height
        result['meta_mode']   = img.mode

        # --- Step 3: Try to extract EXIF data ---
        extracted_exif = {}
        redacted_count = 0
        gps_present = False
        camera_make  = ''
        camera_model = ''
        software     = ''
        datetime_str = ''

        try:
            # Pillow's _getexif() returns a dict of {tag_id: value}
            raw_exif = img._getexif()

            if raw_exif:
                result['meta_has_exif'] = True

                for tag_id, value in raw_exif.items():
                    # Get the human-readable tag name
                    tag_name = TAGS.get(tag_id, str(tag_id))

                    # Convert value to a string-safe representation
                    try:
                        if isinstance(value, bytes):
                            # Try to decode bytes as UTF-8
                            str_value = value.decode('utf-8', errors='replace').strip('\x00')
                        elif isinstance(value, tuple):
                            str_value = str(value)
                        else:
                            str_value = str(value)
                    except Exception:
                        str_value = '[binary data]'

                    if tag_name in SENSITIVE_EXIF_TAG_NAMES:
                        redacted_count += 1
                        if tag_name == 'GPSInfo':
                            gps_present = True
                        continue          # never store or display these values
                    extracted_exif[tag_name] = str_value[:300]

                    # Extract key forensic fields
                    if tag_id == 271:   # Make
                        camera_make = str_value.strip()
                    elif tag_id == 272: # Model
                        camera_model = str_value.strip()
                    elif tag_id == 305: # Software
                        software = str_value.strip()
                    elif tag_id in (306, 36867, 36868): # DateTime
                        if not datetime_str:
                            datetime_str = str_value.strip()

                result['meta_exif_count'] = len(raw_exif)

        except (AttributeError, Exception):
            # PNG and some other formats don't have EXIF or _getexif()
            # Try alternative approaches
            try:
                info = img.info
                if info:
                    for key, val in info.items():
                        if _is_sensitive_info_key(str(key)):
                            redacted_count += 1
                            continue
                        if isinstance(val, str) and len(val) < 500:
                            extracted_exif[str(key)] = val
                    result['meta_has_exif'] = len(extracted_exif) > 0
                    result['meta_exif_count'] = len(extracted_exif)
            except Exception:
                pass

        # --- Step 4: Store key fields ---
        result['meta_camera_make']  = camera_make
        result['meta_camera_model'] = camera_model
        result['meta_software']     = software
        result['meta_datetime']     = datetime_str

        # --- Step 5: Check for editing software ---
        detected_software = ''
        if match_editing_software(software):
            detected_software = software

        result['meta_is_editing_software']   = bool(detected_software)
        result['meta_editing_software_name'] = detected_software

        # --- Step 6: Serialise all EXIF to JSON for storage ---
        # Limit to reasonable size to avoid DB bloat
        if len(extracted_exif) > 50:
            extracted_exif = dict(list(extracted_exif.items())[:50])

        result['meta_raw_json'] = json.dumps(extracted_exif, ensure_ascii=False)

        # --- Step 7: Generate forensic note ---
        result['meta_note'] = _get_metadata_note(
            result['meta_has_exif'],
            result['meta_is_editing_software'],
            software,
            result['meta_format'],
        )

        if redacted_count:
            result['meta_note'] += (
                f" {redacted_count} privacy-sensitive metadata field(s) were present and "
                "deliberately not stored or displayed"
                + (" (including GPS location)." if gps_present else "."))
        result['success'] = True
        logger.info(
            f"Metadata extracted: format={result['meta_format']}, "
            f"has_exif={result['meta_has_exif']}, software='{software}'"
        )

    except ImportError as e:
        result['error'] = f"Metadata extraction requires Pillow: {e}"
        logger.error(result['error'])

    except Exception as e:
        result['error'] = f"Metadata extraction failed: {e}"
        logger.error(result['error'])

    return result


def _format_file_size(size_bytes):
    """Convert bytes to a human-readable string."""
    if size_bytes < 1024:
        return f"{size_bytes} B"
    elif size_bytes < 1024 * 1024:
        return f"{size_bytes / 1024:.1f} KB"
    else:
        return f"{size_bytes / (1024 * 1024):.2f} MB"


def _get_metadata_note(has_exif, is_editing_software, software, img_format):
    """Generate a forensic interpretation note for the metadata."""
    notes = []

    if not has_exif:
        if img_format == 'PNG':
            notes.append(
                "PNG format does not typically embed EXIF data. "
                "The absence of EXIF is expected for PNG files."
            )
        else:
            notes.append(
                "No EXIF metadata was found. This may indicate the image was "
                "downloaded from the internet, screenshot-captured, or had its "
                "metadata stripped. Many ordinary images also lack EXIF (social media, messaging and screenshots strip it), so this is context only."
            )
    else:
        notes.append("EXIF metadata is present.")

    if is_editing_software:
        notes.append(
            f"Editing software was detected in the metadata: '{software}'. "
            "This indicates the image has been processed or edited using image "
            "editing software. Note that camera apps and development tools "
            "also write software tags, so this alone does not prove manipulation."
        )

    notes.append(
        "Metadata is supporting forensic context only — it does not independently "
        "prove or disprove image authenticity."
    )

    return " ".join(notes)
